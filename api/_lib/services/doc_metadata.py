"""Metadatos (Propiedades del archivo) de los documentos que salen del sistema.

Sin esto, cada .docx armado con `Document()` lleva los de la plantilla por
defecto de python-docx (autor "python-docx", descripción "generated by
python-docx", fechas de 2013) y cada carta renderizada desde un `.docx` del
repo lleva el autor de quien lo escribió en Word. LibreOffice copia `dc:creator`
al `/Author` del PDF, así que fijarlo en el .docx alcanza para el PDF.

Un solo lugar para los .docx (`set_docx_metadata`). Los .xlsx pasan por
`xlsx_utils.workbook_bytes`, que usa `ORG_AUTHOR` de acá.
"""
from __future__ import annotations

from datetime import datetime, timezone

ORG_AUTHOR = "FIBA Americas"
# python-docx rechaza una propiedad de más de 255 caracteres (ValueError) y el
# nombre de la competencia viene de la base: se recorta en vez de romper el export.
MAX_PROP_LEN = 255


def clip_title(title) -> str:
    text = str(title or "").strip()
    return text if len(text) <= MAX_PROP_LEN else text[:MAX_PROP_LEN - 3].rstrip() + "..."


def set_docx_metadata(doc, title: str = ""):
    """Autor y último editor = FIBA Americas, título dado, descripción vacía.

    Acepta un `docx.Document` o un `DocxTemplate` ya renderizado (el Document
    vive en `.docx`; llamarlo antes de `render()` no sirve, porque docxtpl
    recarga el archivo al renderizar). Fechas de creación y modificación =
    ahora, revisión 1: es un documento nuevo, no una edición de la plantilla.
    Devuelve el mismo objeto para poder encadenar.
    """
    inner = getattr(doc, "docx", None)
    props = (inner if inner is not None else doc).core_properties
    now = datetime.now(timezone.utc).replace(tzinfo=None, microsecond=0)
    props.author = ORG_AUTHOR
    props.last_modified_by = ORG_AUTHOR
    props.title = clip_title(title)
    props.comments = ""
    props.created = now
    props.modified = now
    props.revision = 1
    return doc
